    /**
     * Capitaliza nombres compuestos adecuadamente en español.
     */
    private function capitalizeName(string $name): string
    {
        $name = mb_strtolower(trim($name), 'UTF-8');
        $words = explode(' ', $name);
        $capitalized = [];
        $lowerArticles = ['de', 'del', 'la', 'las', 'los', 'y', 'en', 'd`', 'd\''];

        foreach ($words as $i => $word) {
            $word = trim($word);
            if ($word === '') continue;
            if ($i > 0 && in_array($word, $lowerArticles)) {
                $capitalized[] = $word;
            } else {
                $capitalized[] = mb_convert_case($word, MB_CASE_TITLE, 'UTF-8');
            }
        }

        return implode(' ', $capitalized);
    }

    /**
     * Separa un nombre completo en Nombres y Apellidos.
     */
    private function splitFullName(string $fullName): array
    {
        $cleaned = preg_replace('/\s+/', ' ', trim($fullName));
        $parts = explode(' ', $cleaned);
        $count = count($parts);

        if ($count <= 1) {
            return [$this->capitalizeName($parts[0] ?? ''), ''];
        } elseif ($count === 2) {
            return [$this->capitalizeName($parts[0]), $this->capitalizeName($parts[1])];
        } elseif ($count === 3) {
            return [$this->capitalizeName($parts[0]), $this->capitalizeName($parts[1] . ' ' . $parts[2])];
        } else {
            // Para 4 o más palabras (ej: MAIRA MARGARITA MORLA PINEDA)
            $firstNames = $parts[0] . ' ' . $parts[1];
            $lastNames = implode(' ', array_slice($parts, 2));
            return [$this->capitalizeName($firstNames), $this->capitalizeName($lastNames)];
        }
    }

